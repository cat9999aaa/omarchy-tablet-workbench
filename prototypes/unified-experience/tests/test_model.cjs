const assert=require('node:assert/strict');
const fs=require('node:fs');const vm=require('node:vm');const path=require('node:path');
const file=path.join(__dirname,'../ExperienceModel.js');
assert.ok(fs.existsSync(file),'ExperienceModel must exist');
const box={};vm.createContext(box);vm.runInContext(fs.readFileSync(file,'utf8'),box);
const plain=x=>JSON.parse(JSON.stringify(x));
assert.deepEqual(plain(box.destinations()).map(x=>x.id),['overview','work','tasks','device','connections','settings']);
let s=box.initialState('normal');const snapshot=JSON.stringify(s);
assert.equal(box.reduce(s,{type:'navigate',id:'not-a-page'}),s);
for(const d of box.destinations()) assert.equal(box.reduce(s,{type:'navigate',id:d.id}).destination,d.id);
assert.equal(box.reduce(s,{type:'shell',id:'a1'}),s);
let hidden=box.reduce(s,{type:'demoHide',id:'a1'});
assert.equal(hidden.windows.find(w=>w.id==='a1').hidden,true);
assert.equal(hidden.windows.find(w=>w.id==='a2').hidden,false);
assert.equal(box.reduce(hidden,{type:'demoRestore',id:'a1'}).windows.find(w=>w.id==='a1').hidden,false);
assert.equal(box.reduce(s,{type:'demoCloseWindow',id:'a1'}).windows.length,2);
assert.deepEqual(plain(box.reduce(s,{type:'demoQuitApplication',id:'a1'}).windows).map(w=>w.id),['b1']);
assert.equal(JSON.stringify(s),snapshot,'reducer must not mutate a source used by a pressed control');
assert.equal(box.reduce(s,{type:'demoHide',id:'absent'}),s);
assert.equal(box.initialState('stale').observations.temperature.health,'stale');
assert.equal(box.initialState('stale').observations.temperature.value,48);
assert.equal(box.initialState('missing-device').observations.light.value,null);
assert.equal(box.initialState('missing-device').observations.light.health,'unavailable');
assert.equal(box.initialState('offline').modelAvailable,false);
assert.match(box.reduce(s,{type:'demoQuitApplication',id:'a1'}).notice,/演示/);
console.log('U1 model: navigation, immutable actions, unknown/stale/offline PASS');
